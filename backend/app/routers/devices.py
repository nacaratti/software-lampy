def _seed_shelf(db: Session) -> None:
    """Adds any shelf catalogue items not yet in the database, by name — so
    growing `_SHELF` (new catalog fibers, etc.) reaches existing installs
    without needing to wipe the devices table."""
    existing_names = {name for (name,) in db.query(Device.name).filter(Device.category == "shelf").all()}
    added = False
    for item in _SHELF:
        if item["name"] in existing_names:
            continue
        data = dict(item)
        params = data.pop("parameters")
        device = Device(**data, parameters=json.dumps(params))
        db.add(device)
        added = True
    if added:
        db.commit()


